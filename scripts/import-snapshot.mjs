// Rebuilds the master data in /private-data/ from a Central Warehouse inventory
// workbook.
//
//   npm run import -- "sample/MCC. PRC. WM. CW Taytay Inventory. 2026 10 05.xlsx"
//
// Then `npm run seed` turns those modules into the SQL that goes into Supabase.
//
// ---------------------------------------------------------------------------
// WHERE THE READING RULES LIVE: src/lib/snapshotRules.js, NOT here.
//
// They moved there on 2026-10-06, when the app grew an in-app Import module (admin →
// Import Data) that pushes a workbook straight into Postgres from the browser. Both
// paths now call the same buildSnapshot(), so a workbook read in the browser and the
// same workbook read here produce identical rows, by construction rather than by
// anybody remembering to update two files. Every assumption the rules make, and every
// workbook that forced one of them, is documented in that module.
//
// WHAT IS STILL THIS SCRIPT'S JOB: the filesystem and the report. It opens the file,
// supplies the reference data from /private-data/, writes the three generated modules,
// and prints the summary — read the report, it is where a bad workbook shows up.
//
// WHEN TO USE THIS RATHER THAN THE APP: when you need the /private-data/ modules
// regenerated — to re-seed a database from scratch (npm run seed), or to inspect a
// workbook without touching live data. For the routine monthly refresh of the live
// site, the in-app importer is now the shorter path and needs no node at all.
// ---------------------------------------------------------------------------
import { writeFileSync } from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { dirname, join, basename } from 'node:path'
import { readWorkbook } from './lib/xlsx.mjs'
import { buildSnapshot, WAREHOUSE } from '../src/lib/snapshotRules.js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const priv = (f) => join(root, 'private-data', f)
const load = (f) => import(pathToFileURL(priv(f)).href)

const src = process.argv[2] || 'sample/MCC. PRC. WM. CW Taytay Inventory. 2026 10 05.xlsx'
const srcPath = join(root, src)

// ---------------------------------------------------------------------------
// Reference data the workbook never carries.
//   item master — trade, item group and material type for every code;
//   projects    — the code behind a project name, where the name matches exactly;
//   previous snapshot — unit price, condition class and bin address, carried forward.
// ---------------------------------------------------------------------------
const { ITEM_MASTER } = await load('itemMaster.js')
const { PROJECTS } = await load('projects.js')
const prevInventory = await load('inventory.js').then((m) => m.inventory).catch(() => [])
const prevSafekeepingSoh = await load('safekeepingSheets.js').then((m) => m.SOH_ROWS).catch(() => [])

const wb = readWorkbook(srcPath)
const snap = buildSnapshot(wb, { itemMaster: ITEM_MASTER, projects: PROJECTS, prevInventory, prevSafekeepingSoh })

const {
  snapshotDate: SNAPSHOT_DATE, split: SPLIT, partition: PARTITION, locationCarried: LOCATION_CARRIED,
  inventory, ledger: LEDGER, soh: SOH_ROWS, incoming: INCOMING_ROWS, outgoing: OUTGOING_ROWS,
  warnings: WARNINGS, stats,
} = snap

const IN_TRANSIT_WINDOW = 14 // documented in the inventory.js banner below

// ---------------------------------------------------------------------------
// Write the modules
// ---------------------------------------------------------------------------
const banner = (extra) => `// AUTO-GENERATED by scripts/import-snapshot.mjs from
// '${basename(srcPath)}' — do not hand-edit. Regenerate with:
//
//   npm run import -- "sample/<workbook>.xlsx"
//
${extra}`

const jsonLines = (rows) => rows.map((r) => `  ${JSON.stringify(r)}`).join(',\n')

writeFileSync(priv('inventory.js'), `${banner(`// Warehouse-owned stock: ${inventory.length} lines from ${SPLIT ? 'sheet "CW SOH"' : 'the rows of sheet "SOH" the ' + PARTITION + ' assigns to the warehouse'}.
// Snapshot ${SNAPSHOT_DATE}.
//
// STRAIGHT FROM THE SHEET: item code, both descriptions, UOM, BOH / In / Out / SOH.
//
// FROM THE ITEM MASTER: trade, item group and material type. The sheet carries no
// Item Group or Trades column; the master resolves every code here.
//
// CARRIED FORWARD from the previous snapshot where this workbook does not give them:
// unit price and condition class. ${stats.unpricedLines} lines could not be priced and sit at zero.
//
// STORAGE LOCATION on ${stats.placedLines} of them, ${LOCATION_CARRIED
  ? `CARRIED FORWARD from the previous snapshot — this workbook has no
// "Item per location bin" sheet, and a bin address does not stop being true because
// a tab was left out of one export. Lines new since then have none.`
  : `read from this workbook's own "Item per location bin" sheet.`}
//
// SYNTHESIZED, deterministically and stably per line: reserved, available, damaged,
// min level, and — for lines the ledger does not reach — last movement. Brand is read
// out of the specific description.
//
// Invariants enforced at generation time:
//   totalQty === availableQty + reservedQty
//   totalQty === beginningQty + periodIn - periodOut   (holds on every source row)
// damagedQty annotates stock counted inside totalQty; incomingQty / outgoingQty are
// unsettled flows from the trailing ${IN_TRANSIT_WINDOW} days of the ledger.`)}
export const WAREHOUSE = '${WAREHOUSE}';
export const SNAPSHOT_DATE = '${SNAPSHOT_DATE}';
export const inventory = [
${jsonLines(inventory)}
];
`, 'utf8')

writeFileSync(priv('ledger.js'), `${banner(`// The warehouse's OWN movement, from ${SPLIT ? 'sheets "CW Incoming" and "CW Outgoing"' : 'the rows of "Incoming" / "Outgoing" the ' + PARTITION + ' assigns to the warehouse'}.
// Project-owned movement is in safekeepingSheets.js instead — the same division the
// stock rows use, so a line's stock and its movement never land on opposite sides.
//
// \`off\` is days before the snapshot date (${SNAPSHOT_DATE}), the same base as
// lastMovementOffset in inventory.js, so 0 is the most recent movement on record.
// Keys are short because this file ships to the browser:
//   dir = 'in' | 'out', off = day offset, c = item code, d = description,
//   q = quantity, u = UOM, p = counterparty project, r = document reference,
//   cls = condition class, cond = condition
//
// ${stats.droppedLedger} warehouse row(s) carry no usable date and are omitted rather than parked on
// an invented day. In: ${stats.ledgerIn}, out: ${stats.ledgerOut}.`)}
export const LEDGER = [
${jsonLines(LEDGER)}
];
`, 'utf8')

writeFileSync(priv('safekeepingSheets.js'), `${banner(`// Project-owned material held at the warehouse, from ${SPLIT
  ? 'the three "Safekeeping …" sheets'
  : 'the rows of "SOH" / "Incoming" / "Outgoing" the ' + PARTITION + ' does not assign to the warehouse'}.
// Snapshot ${SNAPSHOT_DATE}.
//   SOH ${SOH_ROWS.length} rows, Incoming ${INCOMING_ROWS.length}, Outgoing ${OUTGOING_ROWS.length}.
//
// Caveats kept rather than papered over:
//  * No sheet in this workbook prices safekeeping stock, so unitPrice is 0 throughout
//    and the Discounted Price column is dropped entirely.
//  * ${stats.incomingNoCode} of ${INCOMING_ROWS.length} Incoming and ${stats.outgoingNoCode} of ${OUTGOING_ROWS.length} Outgoing rows have NO item code; those
//    lines are identified only by their specific description.
//  * Sheet project names are written loosely and mostly do not match the project
//    master. projectCode is filled ONLY on an exact match (${stats.sohProjectsCoded} of ${SOH_ROWS.length} SOH rows) and
//    left blank otherwise, rather than guessing one site's code onto another's stock.
//  * The sheet's short trade code was dropped in this workbook; \`trade\` is derived
//    back from the item master's trade.`)}
export const SOH_ROWS = [
${jsonLines(SOH_ROWS)}
];

export const INCOMING_ROWS = [
${jsonLines(INCOMING_ROWS)}
];

export const OUTGOING_ROWS = [
${jsonLines(OUTGOING_ROWS)}
];
`, 'utf8')

// ---------------------------------------------------------------------------
// Report
// ---------------------------------------------------------------------------
const money = (n) => '₱' + Math.round(n).toLocaleString('en-PH')
const prevVal = prevInventory.reduce((a, r) => a + (r.inventoryValue || 0), 0)

if (WARNINGS.length) {
  console.log('\n' + '!'.repeat(78))
  console.log('PROBLEMS WITH THE WORKBOOK — read these before trusting the figures below:')
  for (const w of WARNINGS) console.log('  * ' + w)
  console.log('!'.repeat(78))
}

console.log(`\nSnapshot ${SNAPSHOT_DATE}  <-  ${basename(srcPath)}`)
console.log(`  layout ${SPLIT ? 'SPLIT (CW * / Safekeeping * sheets)' : 'MERGED (one SOH / Incoming / Outgoing)'}` +
  `, warehouse-vs-safekeeping decided by ${PARTITION.toUpperCase()}\n`)
console.log(`  inventory            ${String(inventory.length).padStart(5)} lines   (was ${prevInventory.length})`)
console.log(`  ledger               ${String(LEDGER.length).padStart(5)} rows    in ${stats.ledgerIn} / out ${stats.ledgerOut}` +
  (stats.ledgerSpan ? `, spanning ${stats.ledgerSpan.oldest}..${stats.ledgerSpan.newest} days back` : ''))
console.log(`  safekeeping_soh      ${String(SOH_ROWS.length).padStart(5)} lines   (was ${prevSafekeepingSoh.length})`)
console.log(`  safekeeping_incoming ${String(INCOMING_ROWS.length).padStart(5)} rows`)
console.log(`  safekeeping_outgoing ${String(OUTGOING_ROWS.length).padStart(5)} rows`)
console.log(`\n  valuation            ${money(stats.value)}   (previous snapshot ${money(prevVal)})`)
console.log(`  unpriced lines       ${stats.unpricedLines}  holding ${stats.unpricedUnits.toLocaleString()} units`)
console.log(`  no condition class   ${stats.noConditionClass}`)
console.log(`  ${LOCATION_CARRIED ? 'location (CARRIED)' : 'recorded location  '}  ${stats.placedLines} of ${inventory.length} ` +
  `(${Math.round(stats.placedLines / inventory.length * 100)}%), ${stats.multiBinLines} spread over several bays`)
if (LOCATION_CARRIED) {
  console.log(`                       ^ this workbook has NO "Item per location bin" sheet;`)
  console.log(`                         the addresses above are the previous snapshot's.`)
}
console.log(`  units on hand        ${stats.units.toLocaleString()}`)

console.log(`\n  lines per recorded area: ${Object.entries(stats.byArea).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} ${v}`).join(', ')}`)

if (stats.unmatchedProjects.length) {
  console.log(`\n  project names with no code in the master: ${stats.unmatchedProjects.join(', ')}`)
}
if (WARNINGS.length) {
  console.log(`\n  ${WARNINGS.length} problem(s) with the SOURCE workbook are listed at the top of this report.`)
  console.log('  Worth raising with the warehouse team — the import fell back and carried on.')
}
console.log(`\nNext: npm run seed\n`)
